import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const read=(p)=>fs.readFileSync(path.join(process.cwd(),p),"utf8");
const taxonomy=read("server/src/scripts/deployVerbalTaxonomy22.ts");
const migration=read("server/src/scripts/migrateVerbalTaxonomy22.ts");
const legacy=read("server/src/scripts/deployVerbalTaxonomy13.ts");
const ecosystem=read("server/src/scripts/deployVerbalEcosystem.ts");
const mains=[...taxonomy.matchAll(/id:\s*"skill_verbal_(\d{2})"/g)];
const subs=[...taxonomy.matchAll(/id:\s*"(sub_verbal_\d{2}_\d+)"/g)].map(m=>m[1]);
assert.equal(mains.length,22);
assert.equal(subs.length,76);
assert.equal(new Set(subs).size,76);
for(const id of ["sub_verbal_01_1","sub_verbal_08_7","sub_verbal_13_7"]) assert.ok(subs.includes(id));
assert.ok(taxonomy.includes("updateOne("));
assert.ok(!taxonomy.includes("deleteMany("));
assert.ok(migration.includes("afterQuestions !== beforeQuestions"));
assert.ok(migration.includes("foundationDrills !== 76"));
assert.ok(migration.includes("trainingDrills !== 22"));
assert.ok(migration.includes("mockExams !== 5"));
assert.ok(migration.includes("skillIds: [mainSkillId, subSkillId]"));
assert.ok(!migration.includes("quizCol.deleteMany"));
assert.ok(!migration.includes('db.collection("skillprogresses")'));
assert.ok(!migration.includes('db.collection("quizresults")'));
assert.ok(legacy.includes("./deployVerbalTaxonomy22.js"));
assert.ok(ecosystem.includes("ALLOW_DESTRUCTIVE_VERBAL_REBUILD"));
assert.ok(!ecosystem.includes("deleteMany("));
assert.ok(!ecosystem.includes("insertMany("));
console.log("PASS: VERBAL26 taxonomy contract — 22/76 and non-destructive migration.");
