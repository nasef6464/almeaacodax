import { readFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');

const manager = read('dashboards/admin/QuestionBankManager.tsx');
const builder = read('dashboards/admin/builders/UnifiedQuestionBuilder.tsx');
const aiApi = read('services/apiGroups/aiApi.ts');
const aiService = read('services/geminiService.ts');
const aiRoutes = read('server/src/routes/ai.routes.ts');

const checks = [];

const check = (name, assertion) => {
  try {
    assertion();
    checks.push({ name, status: 'PASS' });
  } catch (error) {
    checks.push({ name, status: 'FAIL', details: error instanceof Error ? error.message : String(error) });
  }
};

const includes = (source, fragment) => {
  if (!source.includes(fragment)) throw new Error(`Missing fragment: ${fragment}`);
};

const excludes = (source, fragment) => {
  if (source.includes(fragment)) throw new Error(`Unexpected fragment: ${fragment}`);
};

check('question bank does not advertise the removed fake file/PDF AI action', () => {
  excludes(manager, "alert('تم رفع الملف بنجاح.. جاري استخراج الأسئلة وتصنيفها آلياً!')");
  excludes(manager, 'توليد ذكي من ملف (AI)');
  excludes(manager, 'توليدها تلقائياً من الملازم وملفات PDF باستخدام الذكاء الاصطناعي');
  includes(manager, 'استخراج PDF والملفات غير متاح من هذا المسار حاليًا.');
});

check('question generation stays behind the existing authorized AI endpoint', () => {
  includes(aiApi, 'aiQuestion: (payload: { topic: string }');
  includes(aiApi, '"/ai/question"');
  includes(aiRoutes, 'requireRole(["admin", "teacher", "supervisor"])');
  includes(aiService, 'const response = await api.aiQuestion({ topic });');
});

check('question bank opens a review-first AI draft instead of persisting directly', () => {
  includes(manager, 'const handleCreateAiDraft = () => {');
  includes(manager, 'setGenerateAiDraftOnOpen(true);');
  includes(manager, "resetEditorQuestion('draft');");
  includes(manager, 'setIsEditing(true);');
  includes(manager, 'onClick={handleCreateAiDraft}');
  includes(manager, 'data-testid="question-bank-ai-draft"');

  const handlerStart = manager.indexOf('const handleCreateAiDraft = () => {');
  const handlerEnd = manager.indexOf('const handleEdit =', handlerStart);
  if (handlerStart < 0 || handlerEnd < 0) throw new Error('AI draft handler boundaries not found');
  const handler = manager.slice(handlerStart, handlerEnd);
  excludes(handler, 'addQuestion(');
  excludes(handler, 'updateQuestion(');
});

check('AI draft inherits the currently selected taxonomy context', () => {
  includes(manager, "pathId: selectedPathId || ''");
  includes(manager, "subject: selectedSubjectId || ''");
  includes(manager, "sectionId: selectedSectionId || ''");
  includes(manager, 'skillIds: selectedSkillId ? [selectedSkillId] : []');
  includes(manager, "approvalStatus: approvalStatus || (user.role === 'admin' ? 'approved' : 'pending_review')");
});

check('unified builder auto-generates once on draft open and leaves saving explicit', () => {
  includes(builder, 'generateOnOpen?: boolean;');
  includes(builder, 'generateOnOpen = false');
  includes(builder, 'const hasAutoGenerated = useRef(false);');
  includes(builder, 'if (!generateOnOpen || hasAutoGenerated.current) return;');
  includes(builder, 'void handleGenerateWithFeedback();');
  includes(builder, 'const generated = await generateQuizQuestion(topicName);');

  const generationStart = builder.indexOf('const handleGenerateWithFeedback = async () => {');
  const generationEnd = builder.indexOf('useEffect(() => {\n    if (!generateOnOpen', generationStart);
  if (generationStart < 0 || generationEnd < 0) throw new Error('Builder generation handler boundaries not found');
  const generationHandler = builder.slice(generationStart, generationEnd);
  excludes(generationHandler, 'onSave(');
});

check('generated payload is only copied into editable question state', () => {
  includes(builder, 'setQuestion((prev) => ({');
  includes(builder, 'text: generated.question');
  includes(builder, 'options: generated.options');
  includes(builder, 'correctOptionIndex: generated.correctIndex');
  includes(builder, 'explanation: generated.explanation');
  includes(builder, "type: 'mcq'");
  includes(aiService, 'هذا سؤال مبدئي آمن. راجع السؤال قبل نشره للطلاب.');
});

const failed = checks.filter((item) => item.status === 'FAIL');
console.log(JSON.stringify({
  phase: 'gate6-question-ai-authoring',
  status: failed.length === 0 ? 'PASS' : 'FAIL',
  checks,
}, null, 2));

if (failed.length > 0) process.exit(1);
