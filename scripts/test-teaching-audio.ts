import assert from 'node:assert/strict';
import { BrowserNarrationEngine } from '../components/results/teaching/narrationEngine';
import { prepareTeachingAudio } from '../components/results/teaching/prepareTeachingAudio';

const realWindow = (globalThis as any).window;
const realUtterance = (globalThis as any).SpeechSynthesisUtterance;
const realSetTimeout = globalThis.setTimeout, realClearTimeout = globalThis.clearTimeout;
const timers = new Map<number, { delay: number; run: () => void }>();
let nextTimer = 0;
(globalThis as any).setTimeout = (run: () => void, delay: number) => { timers.set(++nextTimer, { run, delay }); return nextTimer; };
(globalThis as any).clearTimeout = (id: number) => timers.delete(id);
const advance = (delay: number) => { for (const [id, timer] of [...timers]) if (timer.delay <= delay) { timers.delete(id); timer.run(); } };
const spoken: any[] = [];
const listeners = new Set<() => void>();
let voices: any[] = [{ lang: 'ar-SA', localService: true }];
let onSpeak: ((speech: any) => void) | undefined;
let nativePaused = false;
const synth = { getVoices: () => voices, speak: (speech: any) => { spoken.push(speech); onSpeak?.(speech); }, cancel() {}, pause() { nativePaused = true; }, resume() { nativePaused = false; },
  addEventListener: (_: string, fn: () => void) => listeners.add(fn), removeEventListener: (_: string, fn: () => void) => listeners.delete(fn) };
(globalThis as any).window = { speechSynthesis: synth };
(globalThis as any).SpeechSynthesisUtterance = class { constructor(public text: string) {} };
const states: string[] = [];
const narrator = new BrowserNarrationEngine(state => states.push(state));
let completed = 0;
try {
  prepareTeachingAudio();
  assert.equal(spoken.length, 1, 'opening tap must call native speech synchronously, before lazy loading or AI');
  assert.ok(spoken[0].text.trim(), 'activation must use real short speech, not an unreliable empty utterance');
  narrator.speak('نحل السؤال', 'ar-SA', () => completed++);
  const rejected = spoken.at(-1);
  rejected.onerror({ error: 'not-allowed' });
  assert.equal(states.at(-1), 'blocked');
  advance(180000);
  assert.equal(completed, 0, 'blocked audio must not silently count as completed narration');
  const beforeRetry = spoken.length;
  narrator.retry();
  assert.equal(spoken.length, beforeRetry + 1, 'recovery tap must speak synchronously inside the gesture');
  spoken.at(-1).onstart();
  assert.equal(states.at(-1), 'speaking');
  spoken.at(-1).onend();
  assert.equal(completed, 1);
  narrator.speak('خطوة جديدة', 'ar-SA', () => completed++);
  const lateStart = spoken.at(-1).onstart;
  advance(5000);
  assert.equal(states.at(-1), 'blocked', 'detect mobile engines that silently refuse playback');
  lateStart();
  assert.equal(states.at(-1), 'blocked', 'timed-out utterances cannot resurrect old playback');
  narrator.cancel();
  voices = [];
  const count = spoken.length;
  narrator.speak('صوت متأخر', 'ar-SA', () => completed++);
  assert.equal(spoken.length, count, 'wait briefly for asynchronously loaded voices');
  assert.equal(listeners.size, 1);
  voices = [{ lang: 'ar-SA', localService: true }];
  [...listeners].forEach(fn => fn());
  assert.equal(spoken.length, count + 1);
  assert.equal(listeners.size, 0);
  narrator.cancel();
  voices = [];
  narrator.speak('ننتظر الصوت', 'ar-SA', () => completed++);
  narrator.pause();
  voices = [{ lang: 'ar-SA', localService: true }];
  const pausedCount = spoken.length;
  [...listeners].forEach(fn => fn());
  advance(1500);
  assert.equal(spoken.length, pausedCount, 'late voice loading cannot start speech after pause');
  narrator.resume();
  assert.equal(spoken.length, pausedCount + 1);
  assert.equal(nativePaused, false, 'new speech after pause must resume the native synthesizer; cancel alone does not');
  narrator.cancel();
  onSpeak = speech => speech.onerror?.({ error: 'synthesis-unavailable' });
  narrator.speak('غير متاح', 'ar-SA', () => completed++);
  assert.equal(states.at(-1), 'unavailable');
  assert.equal(timers.size, 0, 'synchronous speech failures must leave no watchdog or completion timers');
  narrator.cancel();
  delete (globalThis as any).window.speechSynthesis;
  narrator.speak('لا يوجد محرك', 'ar-SA', () => completed++);
  assert.equal(states.at(-1), 'unavailable');
  assert.equal(completed, 1);
  console.log('PASS teaching audio: tap activation, blocked recovery, silent refusal, delayed voices, pause, cancellation, unsupported engine');
} finally {
  narrator.cancel();
  globalThis.setTimeout = realSetTimeout; globalThis.clearTimeout = realClearTimeout;
  if (realWindow === undefined) delete (globalThis as any).window; else (globalThis as any).window = realWindow;
  if (realUtterance === undefined) delete (globalThis as any).SpeechSynthesisUtterance; else (globalThis as any).SpeechSynthesisUtterance = realUtterance;
}
